// Merges the OpenAPI documents exported by each service (apps/*/openapi.json) into the shared
// contract contracts/api/openapi.yaml. Run with `pnpm contracts:openapi`.
//
// Services share one origin behind the ingress: /api/v1 -> apps/api, /qr/v1 -> apps/qr.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { stringify } from 'yaml';

const root = fileURLToPath(new URL('..', import.meta.url));
const services = ['api', 'qr'];

const merged = {
  openapi: '3.0.0',
  info: {
    title: 'AgriCoop Intelligence API',
    version: '0.1.0',
    description:
      'Generated by `pnpm contracts:openapi` from the NestJS services. Do not edit by hand.\n\n' +
      'Paths under /api/v1 are served by apps/api, paths under /qr/v1 by apps/qr.',
  },
  servers: [{ url: '/' }],
  tags: [],
  paths: {},
  components: { schemas: {}, securitySchemes: {} },
};

for (const service of services) {
  const file = `${root}apps/${service}/openapi.json`;
  if (!existsSync(file)) throw new Error(`Missing ${file}: run the service's openapi:export first`);
  const doc = JSON.parse(readFileSync(file, 'utf8'));

  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    if (merged.paths[path]) throw new Error(`Duplicate path ${path} (${service})`);
    merged.paths[path] = item;
  }
  for (const kind of ['schemas', 'securitySchemes']) {
    for (const [name, schema] of Object.entries(doc.components?.[kind] ?? {})) {
      const existing = merged.components[kind][name];
      if (existing && !isDeepStrictEqual(existing, schema)) {
        throw new Error(`Conflicting components.${kind}.${name} between services`);
      }
      merged.components[kind][name] = schema;
    }
  }
  for (const tag of doc.tags ?? []) {
    if (!merged.tags.some((t) => t.name === tag.name)) merged.tags.push(tag);
  }
}

merged.paths = Object.fromEntries(
  Object.entries(merged.paths).sort(([a], [b]) => a.localeCompare(b)),
);
merged.components.schemas = Object.fromEntries(
  Object.entries(merged.components.schemas).sort(([a], [b]) => a.localeCompare(b)),
);

const header = '# GENERATED by `pnpm contracts:openapi`. Do not edit by hand.\n';
writeFileSync(`${root}contracts/api/openapi.yaml`, header + stringify(merged, { lineWidth: 0 }));
console.warn(`contracts/api/openapi.yaml: ${Object.keys(merged.paths).length} path(s)`);
